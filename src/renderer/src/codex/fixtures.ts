// ── serving them ────────────────────────────────────────────────────────────

const CATALOGS: CodexCatalogMap = {
  cards: CARDS,
  relics: RELICS,
  potions: POTIONS,
  characters: CHARACTERS,
  keywords: KEYWORDS
}

/**
 * How long ago the harness pretends this data was fetched.
 *
 * Measured from `Date.now()` at request time rather than pinned to a date, so
 * the freshness whisper reads "4 min ago" in every screenshot instead of
 * drifting to "yesterday" the day after these fixtures were written.
 */
const PRETEND_AGE_MS = 4 * 60 * 1000

function envelope<T>(data: T): CodexPayload<T> {
  return { data, fetchedAt: Date.now() - PRETEND_AGE_MS, stale: false, apiVersion: 22 }
}

/**
 * Answer one of the store's cache keys, or `null` for a key we have no canned
 * copy of — which `data.ts` treats as "fall through to the real bridge".
 *
 * Bracket and character are parsed out of a metrics key and then deliberately
 * ignored: modelling ten cohorts × six characters as sixty tables would be
 * sixty times the fixture for a harness whose job is to prove the *chrome*
 * renders. Switching cohort in the mock therefore reorders nothing, which is
 * the one honest difference between it and the real tab.
 */
export function fixturePayload(key: string): CodexPayload<unknown> | null {
  const [family, kind] = key.split(':')
  if (family === 'catalog' && isCatalogKind(kind)) return envelope(CATALOGS[kind])
  if (family === 'metrics' && isMetricsKind(kind)) return envelope(TABLES[kind])
  return null
}

function isCatalogKind(kind: string | undefined): kind is CodexCatalogKind {
  return kind !== undefined && kind in CATALOGS
}

function isMetricsKind(kind: string | undefined): kind is CodexKind {
  return kind !== undefined && kind in TABLES
}

