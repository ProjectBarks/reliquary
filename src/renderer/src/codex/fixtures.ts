/**
 * Canned compendium data for the design harness at `#/mock/codex/:view`.
 *
 * **Dev builds only.** Nothing outside `CodexMock.tsx` may import this module,
 * and `CodexMock` itself is only referenced from the `import.meta.env.DEV`
 * branch of the route tree — which the bundler statically folds away, taking
 * these thirty kilobytes of card text with it. `npx electron-vite build` and
 * then grepping `out/renderer` for "Beetle Juice" is the check that this is
 * still true.
 *
 * Every row here was captured verbatim from the live API on 2026-08-13
 * (snapshot v22) rather than invented, for three reasons that all cost nothing
 * to keep:
 *
 *   - The art URLs are real, so the harness paints real card renders off the
 *     CDN. A screenshot of a grid of grey rectangles proves nothing about a
 *     grid of cards.
 *   - The nulls are real. `keywords` is null on most cards, `elo` is null on
 *     every relic and potion row, `character_runs` is null unless a character
 *     filter is on — a fixture that filled those in would let a `·` regression
 *     ship because the harness never showed one.
 *   - The numbers are real, so tiers land where the community site puts them
 *     and the sample-size warnings fire on the entries that deserve them.
 *
 * The selection is deliberately lopsided: twelve cards spanning all six card
 * colours, five rarities and both keyword shapes; six relics across the pools
 * and price bands; four potions. Ascender's Bane appears in the catalog and in
 * **no** metrics table — that is the ungraded case, and it is the one the tier
 * list's "Unrated" band and the detail view's "Not graded in this cohort" line
 * exist to handle.
 *
 * One field is not verbatim, and it is worth knowing why: the API's `upgrade`
 * map returns bare numbers for its flag-ish deltas (`{description_changed: 1}`)
 * while `CodexCard['upgrade']` in `shared/codex.ts` is typed
 * `Record<string, string>`. Those four values are quoted here so the fixture
 * compiles. The type is the thing that is wrong, not the data.
 */

